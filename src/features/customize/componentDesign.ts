export const componentElementId = (id: string, part: string): string => `componente-${id}--${part}`;
export const componentGroupId = (id: string): string => componentElementId(id, 'grupo');

export function componentIdForElement(elementId: string): string | undefined {
  if (!elementId.startsWith('componente-')) return undefined;
  const end = elementId.lastIndexOf('--');
  return end > 'componente-'.length ? elementId.slice('componente-'.length, end) : undefined;
}

export const isComponentElementId = (id: string): boolean => componentIdForElement(id) !== undefined;

/** Structural surfaces that require a material choice; line/hardware previews are excluded. */
export function componentPaintRoles(component:Pick<PatternComponent,'kind'>):string[] {
  if(component.kind==='porta-telefono-camara') return ['cuerpo','marco-superior','marco-izq','marco-der','frente-inferior'];
  return ['bolsillo-solapa-boton','bolsillo-solapa-velcro','bolsillo-cargo'].includes(component.kind)?['cuerpo','solapa']:['cuerpo'];
}

function componentName(component: PatternComponent): string {
  return component.name ?? COMPONENT_OPTIONS.find(option => option.id === component.presetId)?.name ?? COMPONENT_OPTIONS.find(option => option.kind === component.kind)?.name ?? 'Complemento';
}

const clone = <T,>(value: T): T => JSON.parse(JSON.stringify(value)) as T;

function visualView(doc: DesignDoc, component: PatternComponent): DesignView | undefined {
  return doc.views.find(view => view.id === component.placement?.viewId)
    ?? doc.views.find(view => view.source.type === 'pieza' && view.source.pieceId === component.placement?.pieceId)
    ?? doc.views.find(view => view.kind === 'frente' && view.source.type !== 'pieza')
    ?? doc.views.find(view => view.source.type !== 'pieza')
    ?? doc.views[0];
}

/** A flat preview only. Actual sewing contours and allowances belong to the pattern engine. */
function visualElements(component: PatternComponent, view: DesignView, old: Map<string, DesignElement>): DesignElement[] {
  const componentId = component.id;
  const bodyId = componentElementId(componentId, 'cuerpo');
  const oldBody = old.get(bodyId);
  const name = componentName(component);
  const w = component.width, h = component.height;
  const x = component.placement?.x ?? view.minX + view.width * .62;
  const y = component.placement?.y ?? view.minY + view.height * .56;
  const rotation = oldBody?.rotation ?? 0;
  const angle = rotation * Math.PI / 180;
  const flipX = oldBody?.flipX ?? false, flipY = oldBody?.flipY ?? false;
  const transformed = (dx: number, dy: number) => {
    const localX = flipX ? -dx : dx, localY = flipY ? -dy : dy;
    return { x: x + Math.cos(angle) * localX - Math.sin(angle) * localY, y: y + Math.sin(angle) * localX + Math.cos(angle) * localY };
  };
  const part = (partName: string, label: string, width: number, height: number, dx: number, dy: number, partial: Partial<DesignElement> = {}): DesignElement => {
    const id = componentElementId(componentId, partName);
    const previous = old.get(id);
    return newElement(view.id, {
      id, name: `${name} · ${label}`, parentId: componentGroupId(componentId),
      ...transformed(dx, dy), w: width, h: height, rotation, flipX, flipY,
      kind: 'forma', shape: { type: 'rect' },
      fill: previous?.fill ?? { type: 'color', color: '#D5DECD' },
      stroke: previous?.stroke ?? { color: '#314138', width: .8, style: 'solida' },
      // Never export a second applied cutout for a component already generated by the engine.
      technique: 'ninguna', edge: 'na', allowance: 0, backing: 'ninguna',
      locked: previous?.locked ?? false, hidden: previous?.hidden ?? false,
      materialNote: previous?.materialNote,
      ...partial
    });
  };
  const body = part('cuerpo', 'cuerpo', w, h, 0, 0, { edge: 'pespunte' });
  if (component.kind === 'bolsillo-punta') {
    body.kind = 'trazo'; body.shape = undefined;
    body.path = { pts: [[-.5,-.5],[.5,-.5],[.5,.25],[0,.5],[-.5,.25]], closed: true, smooth: false };
  } else if (component.kind === 'bolsillo-redondeado') {
    body.shape = { type: 'rect', radius: Math.min(w,h) * .18 };
  }
  const trimPath=decorationPath(component);
  if(trimPath) { body.kind='trazo';body.shape=undefined;body.vectorPath=trimPath;body.edge='na';
    if(!oldBody) body.fill={type:'color',color:isBoughtTrim(component.kind)?'#E6D4AF':'#C8D6CA'};
    body.materialNote=isBoughtTrim(component.kind)?'Mercería comprada: el motivo es ilustrativo; el PDF incluye metraje y colocación.':body.materialNote;
  }
  const result = [body];
  const folds=decorationFoldPath(component);
  if(folds) result.push(part('pliegues','pliegues de referencia',w,h,0,0,{kind:'trazo',shape:undefined,vectorPath:folds,fill:{type:'ninguno'},stroke:{color:'#74897A',width:.45,style:'solida'}}));
  const line = (id: string, label: string, dx: number, dy: number, width: number, height: number, horizontal = false) => part(id, label, width, height, dx, dy, {
    kind: 'trazo', shape: undefined, fill: { type: 'ninguno' },
    path: { pts: horizontal ? [[-.5,0],[.5,0]] : [[0,-.5],[0,.5]], closed: false, smooth: false },
    stroke: { color: '#314138', width: .8, style: 'pespunte' }
  });
  const hasFlap = ['bolsillo-solapa-boton', 'bolsillo-solapa-velcro', 'bolsillo-cargo'].includes(component.kind);
  if (hasFlap) {
    const flapHeight = Math.min(80, Math.max(35, h * .28));
    result.push(part('solapa', 'solapa', w + 4, flapHeight, 0, -h/2 + flapHeight*.4, { edge: 'pespunte' }));
    if (component.kind !== 'bolsillo-solapa-velcro') result.push(part('boton', 'botón', 12, 12, 0, -h/2 + flapHeight*.5, { shape: { type: 'ellipse' }, fill: old.get(componentElementId(componentId,'boton'))?.fill ?? { type: 'color', color: '#555B4A' } }));
    else result.push(line('velcro','velcro',0,-h/2+flapHeight*.5,w*.4,2,true));
  }
  if (component.kind === 'bolsillo-cierre') {
    result.push(line('cierre','cremallera',0,-h*.34,w*.9,2,true));
    result.push(part('cursor','cursor',7,12,w*.34,-h*.34, { fill: { type: 'color', color: '#B6A87E' } }));
  }
  if (component.kind === 'bolsillo-cargo') {
    result.push(line('fuelle-izq','doblez del fuelle',-w*.36,h*.08,1,h*.75));
    result.push(line('fuelle-der','doblez del fuelle',w*.36,h*.08,1,h*.75));
  }
  if (component.kind === 'porta-herramientas') {
    const channels=component.channels??3;
    for(let i=1;i<channels;i++) result.push(line(`canal-${i}`,`división ${i} de ${channels} canales`,-w/2+w*i/channels,0,1,h*.92));
  }
  if(component.kind==='porta-telefono-camara') {
    const aperture=cameraWindowFor(component);
    const l=aperture.left,t=aperture.top,cw=aperture.width,ch=aperture.height,r=w-l-cw,bottom=h-t-ch;
    result.push(part('marco-superior','banda superior',w,t,0,-h/2+t/2),
      part('marco-izq','banda izquierda',l,ch,-w/2+l/2,-h/2+t+ch/2),
      part('marco-der','banda derecha',r,ch,w/2-r/2,-h/2+t+ch/2),
      part('frente-inferior','frente inferior',w,bottom,0,h/2-bottom/2));
    // The dashed aperture is an opening, never an extra cloth template.
    result.push(part('ventana','abertura de cámara',cw,ch,-w/2+l+cw/2,-h/2+t+ch/2,{
      fill:{type:'ninguno'},stroke:{color:'#53615b',width:.8,style:'pespunte'},
      materialNote:'Abertura libre: las cámaras del teléfono se orientan hacia fuera.'
    }));
    result.push(part('objetivo','cámara de referencia',Math.min(14,cw*.3),Math.min(14,ch*.3),-w/2+l+cw*.3,-h/2+t+ch*.45,{
      shape:{type:'ellipse'},fill:{type:'color',color:'#344b52'},stroke:{color:'#ffffff',width:1,style:'solida'}
    }));
  }
  if (component.kind === 'trabilla' || component.kind === 'porta-martillo') {
    result.push(line('anclaje-superior','anclaje',0,-h*.38,w*.75,1,true));
    result.push(line('anclaje-inferior','anclaje',0,h*.38,w*.75,1,true));
  }
  const priorGroup = old.get(componentGroupId(componentId));
  result.push(newElement(view.id, {
    id: componentGroupId(componentId), name: `${name}${component.quantity > 1 ? ` · ${component.quantity} copias` : ''}`,
    kind: 'grupo', x, y, w, h, rotation, flipX, flipY,
    fill: { type: 'ninguno' }, locked: priorGroup?.locked ?? false,
    hidden: priorGroup?.hidden ?? false,
    materialNote: 'Complemento de confección vinculado a su patrón. Ajusta medidas o elimínalo para actualizar el PDF.'
  }));
  return result;
}

function syncDoc(doc: DesignDoc, components: PatternComponent[]): DesignDoc {
  let source = doc;
  if (!source.views.length && components.length) {
    source = { ...source, views: [{ id: 'vista-complementos', label: 'Composición de complementos', kind: 'detalle', source: { type: 'vacia' }, minX: 0, minY: 0, width: 800, height: 1000, zones: [], refY: 0, refLabel: 'Inicio del espacio de trabajo' }] };
  }
  const old = new Map(source.elements.map(element => [element.id, element]));
  const active = new Set(components.map(component => component.id));
  const known = new Set([...(source.componentSelections ?? []).map(component => component.id), ...active]);
  const unrelated = source.elements.filter(element => {
    const id = componentIdForElement(element.id);
    return !id || !known.has(id);
  });
  const elements: DesignElement[] = [];
  const snapshots = components.map(component => {
    const view = visualView(source, component);
    if (!view) return clone(component);
    const resolved = { ...component, placement: { ...component.placement, viewId: view.id, x: component.placement?.x ?? view.minX + view.width*.62, y: component.placement?.y ?? view.minY + view.height*.56, label: component.placement?.label ?? view.label } };
    elements.push(...visualElements(resolved, view, old));
    return clone(resolved);
  });
  return { ...source, componentSelections: snapshots, elements: [...unrelated, ...elements], updatedAt: nowIso() };
}

export function syncComponentDesign(project: Project): Project;
export function syncComponentDesign(doc: DesignDoc, previous: PatternComponent[], next: PatternComponent[]): DesignDoc;
export function syncComponentDesign(source: Project | DesignDoc, _previous?: PatternComponent[], next?: PatternComponent[]): Project | DesignDoc {
  if ('pattern' in source || 'origin' in source) {
    const project = source as Project;
    const design = syncDoc(project.design ?? newDesign(), project.pattern?.components ?? []);
    return { ...project, design, pattern: project.pattern ? { ...project.pattern, components: clone(design.componentSelections ?? []) } : project.pattern };
  }
  return syncDoc(source as DesignDoc, next ?? []);
}

/** Read the history snapshot, not only live project state, so Undo can restore deleted components. */
export function readComponentsFromDesign(project: Project, doc: DesignDoc, fabrics: Record<string, Fabric> = {}): PatternComponent[] {
  const definitions = doc.componentSelections ?? project.pattern?.components ?? [];
  const registered = doc.componentSelections !== undefined;
  return definitions.flatMap(component => {
    const body = doc.elements.find(element => element.id === componentElementId(component.id, 'cuerpo'));
    if (!body) return registered ? [] : [clone(component)];
    const materials = { ...component.materials };
    for (const role of componentPaintRoles(component)) {
      const part = doc.elements.find(element => element.id === componentElementId(component.id, role));
      if (!part || part.fill.type === 'ninguno') continue;
      if (part.fill.type === 'color') materials[role] = { name: `Color ${part.fill.color} · ${isBoughtTrim(component.kind)?'mercería':'tela'} por elegir`, color: part.fill.color };
      else {
        const fabric = fabrics[part.fill.fabricId];
        const previous = materials[role]?.fabricId === part.fill.fabricId ? materials[role] : undefined;
        materials[role] = { fabricId: part.fill.fabricId, name: fabric?.name ?? previous?.name ?? 'Tela del estudio por identificar', color: fabric?.color ?? previous?.color };
      }
    }
    return [{ ...clone(component), width: body.w, height: body.h, materials,
      placement: { ...component.placement, viewId: body.viewId, x: body.x, y: body.y, label: component.placement?.label ?? doc.views.find(view => view.id === body.viewId)?.label }
    }];
  });
}

export function reconcileComponentDesign(project: Project, fabrics: Record<string, Fabric> = {}): Project {
  if (!project.design || !project.pattern) return project;
  const components = readComponentsFromDesign(project, project.design, fabrics);
  const active = new Set(components.map(component => component.id));
  const known = new Set((project.design.componentSelections ?? []).map(component => component.id));
  // A body deleted directly from Layers also removes its remaining preview pieces.
  const elements = project.design.elements.filter(element => {
    const id = componentIdForElement(element.id);
    return !id || !known.has(id) || active.has(id);
  });
  return { ...project, pattern: { ...project.pattern, components }, design: { ...project.design, elements } };
}

/** Rebuild bounded construction details after a real resize, retaining their chosen fabrics. */
export function normalizeComponentDesign(doc: DesignDoc): DesignDoc {
  let next = doc;
  for (const definition of doc.componentSelections ?? []) {
    const body = next.elements.find(element => element.id === componentElementId(definition.id, 'cuerpo'));
    if (!body || (Math.abs(body.w-definition.width) < 1e-7 && Math.abs(body.h-definition.height) < 1e-7)) continue;
    const component: PatternComponent = { ...definition, width: body.w, height: body.h,
      placement: { ...definition.placement, viewId: body.viewId, x: body.x, y: body.y } };
    const view = visualView(next, component);
    if (!view) continue;
    const old = new Map(next.elements.map(element => [element.id, element]));
    const generated = visualElements(component, view, old);
    const insertAt = next.elements.findIndex(element => componentIdForElement(element.id) === component.id);
    const elements = next.elements.filter(element => componentIdForElement(element.id) !== component.id);
    elements.splice(Math.max(0,insertAt),0,...generated);
    next = { ...next, elements, componentSelections: next.componentSelections?.map(selection => selection.id === component.id ? clone(component) : selection) };
  }
  return next;
}

/** Reject structural edits that a preview cannot safely translate into construction pieces. */
export function componentDesignIssues(project: Project): string[] {
  const doc = project.design;
  if (!doc) return [];
  const components = readComponentsFromDesign(project, doc);
  const old = new Map(doc.elements.map(element => [element.id, element]));
  const issues: string[] = [];
  const knownIds = new Set([...(doc.componentSelections ?? []), ...(project.pattern?.components ?? [])].map(component => component.id));
  if (doc.elements.some(element => { const id = componentIdForElement(element.id); return id && !knownIds.has(id); })) issues.push('Hay un complemento sin su definición de confección. Vuelve a Personalizar para incorporarlo antes de generar el PDF.');
  for (const component of components) {
    const view = visualView(doc, component);
    if (!view) continue;
    const expected = visualElements(component, view, old);
    const body = old.get(componentElementId(component.id, 'cuerpo'));
    const group = old.get(componentGroupId(component.id));
    if (body?.hidden || group?.hidden) issues.push(`${componentName(component)} está oculto en el estudio. Muéstralo o elimínalo para decidir si debe formar parte del PDF.`);
    for (const part of expected.filter(element => element.kind !== 'grupo')) {
      const actual = old.get(part.id);
      if (!actual) { issues.push(`${componentName(component)}: falta una parte de la vista. Vuelve a Personalizar para actualizar el complemento.`); break; }
      const geometry = (element: DesignElement) => JSON.stringify({ kind: element.kind, shape: element.shape ? { ...element.shape, radius: element.shape.type === 'rect' ? undefined : element.shape.radius } : undefined, path: element.path, vectorPath: element.vectorPath, clip: element.clip, maskZoneId: element.maskZoneId });
      if (geometry(actual) !== geometry(part)) {
        issues.push(`${componentName(component)}: la forma o el recorte de una pieza cambió en el estudio. Vuelve a Personalizar para revisar el patrón; el dibujo libre no sustituye su construcción.`); break;
      }
      const same = (a: number, b: number) => Math.abs(a-b) < .05;
      if (![same(actual.x,part.x), same(actual.y,part.y), same(actual.w,part.w), same(actual.h,part.h), same(actual.rotation,part.rotation), actual.flipX === part.flipX, actual.flipY === part.flipY].every(Boolean)) {
        issues.push(`${componentName(component)}: una parte se movió o cambió de tamaño por separado. Ajusta el complemento completo o vuelve a Personalizar para revisar sus piezas.`); break;
      }
    }
  }
  return [...new Set(issues)];
}

export interface ComponentMaterial {
  componentId: string;
  name: string;
  fabricId?: string;
  fabricName?: string;
  color?: string;
}

/** One explicit material entry for each painted structural preview piece; no invented stock or consumption. */
export function componentMaterials(project: Project, fabrics: Record<string, Fabric>): ComponentMaterial[] {
  const doc = project.design;
  if (!doc) return [];
  const active = new Map(readComponentsFromDesign(project, doc).map(component => [component.id, component]));
  return doc.elements.flatMap(element => {
    const id = componentIdForElement(element.id);
    if (!id || !active.has(id) || !componentPaintRoles(active.get(id)!).includes(element.id.slice(element.id.lastIndexOf('--') + 2))) return [];
    const fabric = element.fill.type === 'tela' ? fabrics[element.fill.fabricId] : undefined;
    return [{ componentId: id, name: element.name, fabricId: fabric?.id,
      fabricName: fabric?.name ?? (isBoughtTrim(active.get(id)!.kind) ? 'Mercería por elegir' : element.fill.type === 'color' ? 'Tela por elegir' : 'Tela por definir'),
      color: element.fill.type === 'color' ? element.fill.color : fabric?.color
    }];
  });
}
